"""Generate redistributable PDF fixtures; no user documents or copyrighted textbooks."""
from pathlib import Path
import math
from PIL import Image, ImageDraw, ImageFont
from reportlab.pdfgen import canvas
from reportlab.pdfbase import pdfmetrics
from reportlab.pdfbase.ttfonts import TTFont
from reportlab.lib.utils import ImageReader
from pypdf import PdfReader, PdfWriter

out = Path(__file__).resolve().parents[1] / "build-fixtures"
out.mkdir(exist_ok=True)
font = Path("/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf")
if not font.exists():
    raise RuntimeError("Install DejaVu Sans to generate the embedded-font fixtures")
pdfmetrics.registerFont(TTFont("Math", str(font)))
cjk = Path("/workspace/toolchain/root/usr/share/fonts/truetype/wqy/wqy-microhei.ttc")
if cjk.exists():
    pdfmetrics.registerFont(TTFont("CJK", str(cjk), subfontIndex=0))
c = canvas.Canvas(str(out / "teaching-sample.pdf"), pagesize=(612, 792), pageCompression=1)
c.setTitle("PaperView teaching fixture")
c.bookmarkPage("math")
c.addOutlineEntry("Mathematics / Physics / Chemistry", "math", 0)
c.setFont("Math", 23)
c.drawString(45, 738, "Equation rendering test")
if cjk.exists():
    c.setFont("CJK", 16)
    c.drawString(45, 700, "数学 · 物理 · 化学：教学文档显示测试")
c.setFont("Math", 19)
for y, text in [(649, "x² + y² = r²"), (606, "∫₀¹ x² dx = ⅓"), (563, "α + β + γ = π"), (520, "E = mc²     F = ma"), (477, "H₂SO₄ + 2NaOH → Na₂SO₄ + 2H₂O")]:
    c.drawString(45, y, text)
c.drawString(65, 405, "−b ± √(b² − 4ac)")
c.line(45, 394, 270, 394)
c.drawString(140, 368, "2a")
c.setStrokeColorRGB(.12, .3, .65)
c.setLineWidth(1.3)
points = [(415 + 48 * math.cos(i * math.pi / 3), 350 + 48 * math.sin(i * math.pi / 3)) for i in range(6)]
for i in range(6):
    c.line(*points[i], *points[(i + 1) % 6])
c.circle(415, 350, 31)
c.setFont("Math", 12)
c.drawString(45, 260, "Embedded Unicode fonts, thin vector lines, superscripts and subscripts.")
c.setFillAlpha(.35)
c.setFillColorRGB(1, .8, 0)
c.rect(45, 598, 200, 25, stroke=0, fill=1)
c.setFillAlpha(1)
c.setFillColorRGB(0, 0, 0)
c.drawString(45, 60, "This PDF is generated by the project's test fixture script.")
c.showPage()
c.bookmarkPage("scan")
c.addOutlineEntry("Scanned page / large bitmap", "scan", 0)
im = Image.new("RGB", (1800, 2400), "#fffef8")
d = ImageDraw.Draw(im)
f = ImageFont.truetype(str(font), 50)
d.text((120, 100), "Scanned teaching page", font=f, fill="#172554")
for i in range(23):
    y = 250 + i * 78
    d.text((120, y), f"{i+1:02}.  x² + {i+2}x + 1 = 0     E = mc²", font=f, fill="#1f2937")
for x in range(120, 1650, 70):
    d.line((x, 2140, x, 2330), fill="#cbd5e1", width=2)
for y in range(2140, 2340, 30):
    d.line((120, y, 1650, y), fill="#cbd5e1", width=2)
c.drawImage(ImageReader(im), 0, 0, 612, 792)
c.showPage()
c.setPageSize((792, 612))
c.bookmarkPage("landscape")
c.addOutlineEntry("Landscape / vector diagram", "landscape", 0)
c.setFont("Math", 24)
c.drawString(50, 555, "Equation: wave motion — landscape")
c.setLineWidth(.5)
for x in range(50, 750, 20):
    c.setStrokeColorRGB(.85, .88, .92)
    c.line(x, 100, x, 500)
for y in range(100, 510, 20):
    c.line(50, y, 750, y)
c.setStrokeColorRGB(.1, .3, .8)
c.setLineWidth(1.2)
path = c.beginPath()
for x in range(50, 751):
    y = 300 + 120 * math.sin((x - 50) / 45)
    if x == 50:
        path.moveTo(x, y)
    else:
        path.lineTo(x, y)
c.drawPath(path)
c.save()
reader = PdfReader(out / "teaching-sample.pdf")
writer = PdfWriter()
for page in reader.pages:
    writer.add_page(page)
writer.encrypt("classroom", algorithm="AES-256")
writer.write(out / "encrypted.pdf")
writer = PdfWriter()
for i in range(100):
    for page in reader.pages:
        writer.add_page(page)
writer.write(out / "large-300-pages.pdf")
(out / "malformed.pdf").write_bytes(b"%PDF-1.7\nThis deliberately is not a valid PDF.\n")
print(out)
